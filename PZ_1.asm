#Напишите программу на ассемблере RISC-V ,
#которая принимает на вход целое число x и выводит 1,
#если оно соответствует номеру студента в списке группы и  0,
#если не совпадает.
.text
.globl main
main:
    li a7, 5
    ecall
    
    addi a0, a0, -20
    seqz a0, a0
    li a7, 1
    ecall
    
exit:
    li a7, 10
    ecall